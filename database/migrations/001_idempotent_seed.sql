    SELECT USER_ID INTO v_admin_id FROM USERS WHERE USERNAME = 'admin';
    SELECT USER_ID INTO v_recep_id FROM USERS WHERE USERNAME = 'reception1';

    -- Resolve guest IDs
    SELECT GUEST_ID INTO v_guest1_id FROM GUESTS WHERE ID_NUMBER = 'P12345678';
    SELECT GUEST_ID INTO v_guest2_id FROM GUESTS WHERE ID_NUMBER = 'ES987654';
    SELECT GUEST_ID INTO v_guest3_id FROM GUESTS WHERE ID_NUMBER = 'JP112233';

    -- Resolve room IDs
    SELECT ROOM_ID INTO v_room_201_id FROM ROOMS WHERE ROOM_NUMBER = '201';
    SELECT ROOM_ID INTO v_room_301_id FROM ROOMS WHERE ROOM_NUMBER = '301';
    SELECT ROOM_ID INTO v_room_501_id FROM ROOMS WHERE ROOM_NUMBER = '501';


        VALUES (v_booking1_id, v_recep_id, 'Guest arrived on time, passport verified')
        RETURNING CHECKIN_ID INTO v_checkin1_id;

        INSERT INTO CHECKOUTS (CHECKIN_ID, CHECKED_OUT_BY, NOTES)
        VALUES (v_checkin1_id, v_recep_id, 'Guest satisfied, paid in full');

        INSERT INTO INVOICES (BOOKING_ID, GUEST_ID, STATUS)
        VALUES (v_booking1_id, v_guest1_id, 'PAID')
        RETURNING INVOICE_ID INTO v_invoice1_id;


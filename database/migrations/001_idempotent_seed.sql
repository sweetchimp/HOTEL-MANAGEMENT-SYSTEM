        VALUES (v_invoice1_id, 'Room 201 - Standard (3 nights)', 1, 240.00);

        INSERT INTO INVOICE_ITEMS (INVOICE_ID, DESCRIPTION, QUANTITY, UNIT_PRICE)
        VALUES (v_invoice1_id, 'Minibar charges', 2, 25.00);

